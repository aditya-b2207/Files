   OR (SELECT SUM(SAPBalance) FROM #LedgerOpeningBalance) <> -120627135
   OR (SELECT COUNT(*) FROM #LedgerOpeningBalance WHERE DC = 'S') <> 16
   OR (SELECT COUNT(*) FROM #LedgerOpeningBalance WHERE DC = 'H') <> 555
   OR EXISTS (SELECT 1 FROM #LedgerOpeningBalance
              WHERE DC <> CASE WHEN SAPBalance > 0 THEN 'S' ELSE 'H' END)
    THROW 50002, 'Source validation failed.', 1;

DECLARE @OpeningDate DATE = '20261101';
DECLARE @UpdateBy NVARCHAR(10) = '2026-11-25';
DECLARE @Inserted INT;

BEGIN TRY
    BEGIN TRANSACTION;

    -- Prevent a second November opening-balance import; do not touch old dates.
    IF EXISTS (
        SELECT 1
        FROM dbo.TB_CustomerLedger WITH (UPDLOCK, HOLDLOCK)
        WHERE CompanyCode = 1054
          AND Document_Type = 'AB'
          AND Document_Number = '0000000000'
          AND Posting_Date = @OpeningDate
    )
        THROW 50003, 'November opening balance records already exist. Review before retrying.', 1;

    INSERT INTO dbo.TB_CustomerLedger (
        CompanyCode, CustomerCode, Document_Type, Document_Number,
        Credit_Control_Area, Document_Date, Net_Due_Date, Posting_Date,
        Credit_Control_Area_Currency, Baseline_Payment_Date,
        Amount_in_Local_Currency, Clearing_Date, Clearing_Document,
        Assignment, Reference, [Text], Account, Document_Header_Text,
        UserCode, Arrears_by_Net_Due_Date, GLAccount, UpdateBy, DC
    )
    SELECT
        1054, CustomerCode, N'AB', N'0000000000', N'AGMH',
        @OpeningDate, @OpeningDate, @OpeningDate, NULL, @OpeningDate,
        ABS(SAPBalance), NULL, NULL, NULL, NULL, N'Opening Balance',
        N'23580001', N'Opening Balance', NULL, 0, '23580001', @UpdateBy, DC
    FROM #LedgerOpeningBalance;

    SET @Inserted = @@ROWCOUNT;
    IF @Inserted <> 571
        THROW 50004, 'Unexpected inserted row count.', 1;

    IF (SELECT COUNT(*) FROM dbo.TB_CustomerLedger
        WHERE CompanyCode = 1054 AND Document_Type = 'AB'
          AND Document_Number = '0000000000' AND Posting_Date = @OpeningDate) <> 571
       OR EXISTS (
           SELECT CustomerCode, ABS(SAPBalance), DC FROM #LedgerOpeningBalance
           EXCEPT
           SELECT CustomerCode, Amount_in_Local_Currency, DC
           FROM dbo.TB_CustomerLedger
           WHERE CompanyCode = 1054 AND Document_Type = 'AB'
             AND Document_Number = '0000000000' AND Posting_Date = @OpeningDate
       )
        THROW 50005, 'Inserted data validation failed.', 1;

    COMMIT TRANSACTION;
    SELECT @Inserted AS InsertedRecords, 'Success' AS Result;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

SELECT DC, COUNT(*) AS CustomerCount,
       SUM(Amount_in_Local_Currency) AS TotalAmount,
       SUM(CASE WHEN DC = 'H' THEN -Amount_in_Local_Currency
                ELSE Amount_in_Local_Currency END) AS SignedSAPBalance
FROM dbo.TB_CustomerLedger
WHERE CompanyCode = 1054 AND Document_Type = 'AB'
  AND Document_Number = '0000000000' AND Posting_Date = @OpeningDate
GROUP BY DC;
